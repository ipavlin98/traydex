use serde::{Deserialize, Serialize};
use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Clone, Copy, PartialEq, Serialize, Deserialize)]
pub enum Language {
    English,
    Chinese,
    Hindi,
    Spanish,
    French,
    Russian,
}

#[cfg(not(test))]
static CURRENT: AtomicU8 = AtomicU8::new(0);

#[cfg(test)]
thread_local! {
    static CURRENT: AtomicU8 = const { AtomicU8::new(0) };
}

#[cfg(not(test))]
fn with_current<R>(f: impl FnOnce(&AtomicU8) -> R) -> R {
    f(&CURRENT)
}

#[cfg(test)]
fn with_current<R>(f: impl FnOnce(&AtomicU8) -> R) -> R {
    CURRENT.with(f)
}

impl Language {
    pub const ALL: [Language; 6] =
        [Language::English, Language::Chinese, Language::Hindi, Language::Spanish, Language::French, Language::Russian];

    pub fn native_name(self) -> &'static str {
        match self {
            Language::English => "English",
            Language::Chinese => "简体中文",
            Language::Hindi => "हिन्दी",
            Language::Spanish => "Español",
            Language::French => "Français",
            Language::Russian => "Русский",
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Language::English => "en",
            Language::Chinese => "zh",
            Language::Hindi => "hi",
            Language::Spanish => "es",
            Language::French => "fr",
            Language::Russian => "ru",
        }
    }

    pub fn font(self) -> &'static str {
        match self {
            Language::Chinese => "Microsoft YaHei UI",
            Language::Hindi => "Nirmala UI",
            _ => "Segoe UI",
        }
    }

    pub fn system() -> Self {
        let id = crate::os::ui_language() & 0x3ff;
        match id {
            0x04 => Language::Chinese,
            0x39 => Language::Hindi,
            0x0a => Language::Spanish,
            0x0c => Language::French,
            0x19 => Language::Russian,
            _ => Language::English,
        }
    }

    fn strings(self) -> &'static Strings {
        match self {
            Language::English => &en::EN,
            Language::Chinese => &zh::ZH,
            Language::Hindi => &hi::HI,
            Language::Spanish => &es::ES,
            Language::French => &fr::FR,
            Language::Russian => &ru::RU,
        }
    }
}

pub fn set(language: Language) {
    let index = Language::ALL.iter().position(|l| *l == language).unwrap_or(0);
    with_current(|current| current.store(index as u8, Ordering::Relaxed));
}

pub fn current() -> Language {
    Language::ALL[with_current(|current| current.load(Ordering::Relaxed)) as usize % Language::ALL.len()]
}

pub fn tr() -> &'static Strings {
    current().strings()
}

pub fn fill(template: &str, value: impl std::fmt::Display) -> String {
    template.replacen("{}", &value.to_string(), 1)
}

